/**
 * Convert a world-atlas geo.properties.name to the dropdown country name.
 */
export function geoNameToDropdown(geoName) {
  if (!geoName) return ''
  return GEO_TO_DROPDOWN[geoName] || geoName
}

/**
 * Convert a dropdown country name to world-atlas geo.properties.name.
 */
export function dropdownToGeoName(dropdownName) {
  if (!dropdownName) return ''
  return DROPDOWN_TO_GEO[dropdownName] || dropdownName
}
